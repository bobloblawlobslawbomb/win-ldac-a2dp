<#
.SYNOPSIS
    Claims a Bluetooth radio for WinUSB so win-ldac-a2dp can drive it — no Zadig.

.DESCRIPTION
    Windows' inbox Bluetooth stack owns the radio. This assigns the inbox WinUSB
    driver to one radio instead, which takes it away from Windows Bluetooth
    entirely (that is the point: we speak HCI ourselves).

    It generates a minimal WinUSB INF for the chosen radio's hardware ID and
    installs it with pnputil.

    !! UNTESTED !!
    Written without a machine available to verify against. Read what it will do
    before running it. Revert with scripts\restore-bluetooth.ps1.

.EXAMPLE
    .\setup.ps1
    .\setup.ps1 -InstanceId 'USB\VID_8087&PID_0032\8&F2CB6FA&0&14' -Yes
#>
[CmdletBinding()]
param(
    [string]$InstanceId,
    [switch]$Yes
)

$ErrorActionPreference = 'Stop'

function Assert-Admin {
    $id = [Security.Principal.WindowsIdentity]::GetCurrent()
    $isAdmin = ([Security.Principal.WindowsPrincipal]$id).IsInRole(
        [Security.Principal.WindowsBuiltInRole]::Administrator)
    if (-not $isAdmin) { throw "Run this from an elevated PowerShell (Run as Administrator)." }
}

function Get-RadioCandidates {
    $out = @()
    foreach ($d in (Get-PnpDevice -PresentOnly -ErrorAction SilentlyContinue)) {
        $svc = (Get-PnpDeviceProperty -InstanceId $d.InstanceId -KeyName 'DEVPKEY_Device_Service' -ErrorAction SilentlyContinue).Data
        if ($d.InstanceId -like 'USB\VID_*' -and $d.Class -in @('Bluetooth', 'USB', 'USBDevice')) {
            $out += [pscustomobject]@{
                Index        = 0
                Name         = $d.FriendlyName
                Service      = $svc
                Status       = $d.Status
                InstanceId   = $d.InstanceId
                HardwareId   = ($d.InstanceId -split '\\')[0..1] -join '\'
            }
        }
    }
    $i = 0
    foreach ($r in $out) { $r.Index = $i++ }
    return $out
}

function New-WinUsbInf {
    param([string]$HardwareId, [string]$Path)

    $body = @"
; Generated by win-ldac-a2dp setup.ps1 — binds an existing radio to inbox WinUSB.
[Version]
Signature           = "`$Windows NT`$"
Class               = USBDevice
ClassGuid           = {88BAE032-5A81-49f0-BC3D-A4FF138216D6}
Provider            = %ProviderName%
DriverVer           = 01/01/2026,1.0.0.0

[Manufacturer]
%ProviderName%      = DeviceList,NTamd64

[DeviceList.NTamd64]
%DeviceName%        = WinUSB_Install, $HardwareId

[WinUSB_Install]
Include             = winusb.inf
Needs               = WINUSB.NT

[WinUSB_Install.Services]
Include             = winusb.inf
Needs               = WINUSB.NT.Services

[WinUSB_Install.HW]
AddReg              = WinUSB_Install_HW.AddReg

[WinUSB_Install_HW.AddReg]

[Strings]
ProviderName        = "win-ldac-a2dp"
DeviceName          = "Bluetooth Radio (WinUSB) — win-ldac-a2dp"
"@
    Set-Content -Path $Path -Value $body -Encoding ASCII
}

Assert-Admin

Write-Host "win-ldac-a2dp — claim a Bluetooth radio for WinUSB" -ForegroundColor Cyan
Write-Host ""
Write-Host "This will DISABLE normal Windows Bluetooth for the chosen radio until you" -ForegroundColor Yellow
Write-Host "undo it with scripts\restore-bluetooth.ps1. Bluetooth mice, keyboards and" -ForegroundColor Yellow
Write-Host "headset microphones on that radio will stop working." -ForegroundColor Yellow
Write-Host ""

$radios = @(Get-RadioCandidates)
if (-not $radios) { throw "No USB Bluetooth radio found. Is the adapter plugged in?" }

if (-not $InstanceId) {
    $radios | Select-Object Index, Name, Status, Service, HardwareId |
        Format-Table -AutoSize -Wrap | Out-String | Write-Host
    $pick = Read-Host "Which radio? [number]"
    $sel = $radios | Where-Object { "$($_.Index)" -eq "$pick" }
    if (-not $sel) { throw "No radio selected." }
    $InstanceId = $sel.InstanceId
} else {
    $sel = $radios | Where-Object { $_.InstanceId -eq $InstanceId }
    if (-not $sel) { throw "InstanceId not found among radios: $InstanceId" }
}

if ($sel.Service -eq 'WinUSB') {
    Write-Host "Already bound to WinUSB — nothing to do." -ForegroundColor Green
    return
}

Write-Host ""
Write-Host "Target : $($sel.Name)" -ForegroundColor Cyan
Write-Host "Device : $($sel.InstanceId)"
Write-Host "Driver : $($sel.Service)"
Write-Host ""

if (-not $Yes) {
    $confirm = Read-Host "Proceed and hand this radio to WinUSB? [y/N]"
    if ($confirm -notmatch '^(y|yes)$') { Write-Host "Cancelled."; return }
}

$infDir = Join-Path $env:TEMP 'win-ldac-a2dp-inf'
New-Item -ItemType Directory -Force -Path $infDir | Out-Null
$inf = Join-Path $infDir 'ldac_winusb.inf'
New-WinUsbInf -HardwareId $sel.HardwareId -Path $inf
Write-Host "Wrote $inf" -ForegroundColor Gray

Write-Host "Installing driver package..." -ForegroundColor Yellow
$pnputil = & pnputil /add-driver $inf /install 2>&1
$pnputil | ForEach-Object { "  $_" }

Write-Host "Rescanning devices..." -ForegroundColor Yellow
& pnputil /scan-devices | Out-Null
Start-Sleep -Seconds 3

$now = (Get-PnpDeviceProperty -InstanceId $InstanceId -KeyName 'DEVPKEY_Device_Service' -ErrorAction SilentlyContinue).Data
Write-Host ""
if ($now -eq 'WinUSB') {
    Write-Host "Done: $InstanceId is now bound to WinUSB." -ForegroundColor Green
    Write-Host ""
    Write-Host "Next:" -ForegroundColor Cyan
    Write-Host "  1. Put your headphones in pairing mode"
    Write-Host "  2. .\a2dp_source_demo.exe --scan"
    Write-Host "  3. .\a2dp_source_demo.exe --addr <address> --mode HQ --source system"
    Write-Host ""
    Write-Host "To hand the radio back later: .\scripts\restore-bluetooth.ps1 -InstanceId '$InstanceId'" -ForegroundColor Gray
} else {
    Write-Host "Driver is now '$now', not WinUSB." -ForegroundColor Yellow
    Write-Host "Windows may refuse an unsigned INF. Options:" -ForegroundColor Yellow
    Write-Host "  - check Device Manager for a warning on the radio"
    Write-Host "  - use Zadig instead (Options -> List All Devices -> WinUSB)"
    Write-Host "  - reboot and re-run if the driver bound but did not start"
}
